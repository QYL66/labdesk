一件事的处理进展：故障与排查、正在办的申请、正在比较或犹豫的方案、就这件事做出的决定。事情办完就过期，进度以工单、申请单等记录为准。
系统里已有权威来源的事实（账号资料、预约记录、权限、实验室规程等），记进来只会与权威源不一致。
