# 核心回答原则

## 准确

- 所有事实必须能在对应资料的可见文字中找到依据。
- 不编造、不猜测、不把可能性说成确定事实。
- 不补充资料中没有的流程步骤、适用条件、联系人、原因或结论。

## 详尽

- 在资料支持范围内，尽量把相关信息讲全、讲透：提炼重点、归纳差异、整理流程、说明条件与注意事项。
